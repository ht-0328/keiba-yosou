"""近走の文: 馬の過去走を1走ずつ定型の文にし、負けた走には敗因の候補を添える部品。

今週の予想・全頭評価・次のレースの予想が、印や強み・弱みに添える「なぜそうなったか」の文を、
JV-Data にある事実（着順・人気・着差・コーナーの順位・上がり・ペース・馬場・馬体重）と回顧の不利判定から機械的に作る。
厩舎の事情や進路の内外のように JV-Data に無いことは書かない。

| クラス | 仕事 |
|---|---|
| ``PastRunRepository`` | 対象の馬の、基準日より前の中央の出走を事実表から読む（1 SQL） |
| ``RacePaceRepository`` | レースのペース（前3F を同じ条件の前のレースと比べた z）を読む（1 SQL） |
| ``ReviewNoteRepository`` | 回顧の表3「馬の回顧ノート」から不利の種類と程度を読む |
| ``CardHorseRepository`` | 出馬表（出走馬名表）の出走馬を読む（1 SQL） |
| ``PastRunReader`` | 上の3つを合わせて、馬ごとの ``PastRun`` の並び（古い順）にする |
| ``PastRun`` | 1走の事実（型付き）と、位置・ペースの言葉 |
| ``Record`` | 走の束の着別度数（1着-2着-3着-着外）と3着以内率 |
| ``RunSentence`` | 1走を文にする |
| ``RecordContrast`` | 2つの条件の成績の対比（こちらの側がはっきり悪いときだけ両方の着別度数を返す） |
| ``LossReason`` | 4着以下の走の敗因の候補（回顧の不利・初めての条件・前走からの変化・その走までの対比・休み明け・馬体重）を文にする |
| ``EvaluationWords`` | 近走の評価のことば（上向き・大敗続き。研究「近走の文の評価のことば」で次走の成績との関係を確かめたものだけ）を文にする |
| ``PastRunStory`` | 馬1頭の近走（既定 5走）の文と敗因の候補、評価のことばをまとめる |
| ``StoryWriter`` | ``HorseStory`` を Markdown の行にする |
"""
